//! Pure domain model for a discovered mutation site.
//!
//! This module is **Core/domain** (design.md → inward dependency flow): it holds
//! no fs/process/argv/clap dependencies and never `use`s the runner, coverage, or
//! CLI layers. It describes only *what* a mutation site is — its taxonomy class,
//! byte span, line, and enclosing function — leaving the actual byte-mutation
//! mapping to the operators layer (T9) and the AST walk to [`crate::scanner`].

use std::ops::Range;

/// Taxonomy category of a mutation site.
///
/// The discovered classes are the feature file's **universal + arithmetic-parity**
/// set (S3), the **arithmetic idiomatic completions** (S4: `/`, `%`, and the
/// compound-assignment operators), and the **token-level S6 Rust-specific**
/// classes (T13a: float constants, bitwise/shift operators, predicate-method
/// swaps) plus the **structural S6** classes that still fit one span (T13b:
/// `Some(x) → None`, `Ok(x) → Err(x)`, `.unwrap() → .unwrap_or_default()`,
/// `expr? → expr.unwrap()`, arm-guard drop). Each class maps to one or more
/// concrete [`Operator`]s. S6's `match`-arm **body swap** needs two disjoint
/// spans and remains out of scope (T13c).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SiteKind {
    /// Binary arithmetic operator — `+`, `-`, `*` (parity) and `/`, `%` (S4).
    Arithmetic,
    /// Ordering comparison — `>`, `>=`, `<`, `<=`.
    Comparison,
    /// Equality comparison — `==`, `!=`.
    Equality,
    /// Boolean literal — `true`, `false`.
    BooleanLiteral,
    /// Short-circuit logical operator — `&&`, `||`.
    Logical,
    /// Integer constant `0` or `1`.
    Constant,
    /// Compound-assignment operator — `+=`, `-=`, `*=`, `/=`, `%=`.
    CompoundAssignment,
    /// Float constant `0.0` or `1.0` (S6).
    FloatConstant,
    /// Bitwise or shift operator — `&`, `|`, `^`, `<<`, `>>` (S6).
    Bitwise,
    /// Zero-argument predicate method — `is_some`, `is_none`, `is_ok`, `is_err`
    /// (S6). The site's span is the **method name identifier only**.
    PredicateMethod,
    /// `Some(x)` constructor call (S6). The site's span is the **whole call
    /// expression**, which the mutation replaces with `None`.
    OptionConstructor,
    /// `Ok(x)` constructor call (S6). The site's span is the **`Ok` identifier
    /// only**, so the bound value survives into `Err(x)`.
    ResultConstructor,
    /// `.unwrap()` call (S6). The site's span is the **method name identifier
    /// only**.
    UnwrapCall,
    /// The `?` operator (S6). The site's span is the **`?` token only**.
    TryOperator,
    /// A `match` arm's guard (S6). The site's span covers `if <guard>`, which the
    /// mutation drops.
    MatchArm,
}

/// Declares the [`Operator`] enum and its [`Operator::ALL`] roster from a single
/// variant list.
///
/// `ALL` is what every guardrail test iterates, so an operator missing from it is
/// an operator nobody checks. Generating both from one list makes that omission
/// **impossible to express**: there is no second place to forget.
macro_rules! declare_operators {
    ($( $(#[$doc:meta])* $variant:ident ),+ $(,)?) => {
        /// The exact operator or token found at a site.
        ///
        /// This is the precise classification the mutation mapping (T9) needs to
        /// compute the mutated bytes; the coarser [`SiteKind`] is derived from it
        /// via [`Operator::kind`]. T4 does **not** perform any mutation — it only
        /// records which operator/token was found.
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub enum Operator {
            $( $(#[$doc])* $variant, )+
        }

        impl Operator {
            /// Every operator, in declaration order.
            ///
            /// Generated by `declare_operators!` from the same variant list as the
            /// enum itself, so it cannot fall behind: declaring a variant *is*
            /// listing it here. Guardrail tests iterate this array.
            pub const ALL: [Operator; [$(Operator::$variant),+].len()] =
                [$(Operator::$variant),+];
        }
    };
}

